/** Seeded LCG (test data only): the same jobs on every run. */
function lcg(seed: number): () => number {
  let x = seed >>> 0;
  return () => {
    x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
    return x / 2 ** 32;
  };
}

/** `n` single-size jobs (2800 × 2070), gap 0/0.1/2/8, Ø6/8/10, all three modes. */
function singleSizeJobs(n: number): NestingInput[] {
  const rnd = lcg(56);
  const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)] as T;
  const int = (a: number, b: number) => a + Math.floor(rnd() * (b - a + 1));
  return Array.from({ length: n }, () => {
    const count = int(1, 12);
    return {
      sheet: { width: 2800, height: 2070 },
      parts: Array.from({ length: count }, (_, i) => ({
        id: `p${i}`,
        w: int(20, 1400),
        h: int(20, 1000),
        qty: int(1, 6),
        grainLock: rnd() < 0.4,
      })),
      gap: pick([0, 0.1, 2, 8]),
      margin: 10,
      toolDiameter: pick([6, 8, 10]),
      mode: pick(['minWaste', 'fastest', 'minToolChanges'] as const),
      locked: [],
    };
  });
}

/** FNV-1a of a string, hex (a short fingerprint of a result). */
function fingerprint(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

